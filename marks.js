const MARK_LABEL = {tc:"三冠王", mvp:"その年のMVP", war:"従軍"};
function playerMarks(p){
  const m = [];
  if(!p) return m;
  if(p.tc) m.push("tc");
  if(MARK_MVP.has(p.name + "@" + p.year)) m.push("mvp");
  if(MARK_WAR.has(p.name)) m.push("war");
  return m;
}
